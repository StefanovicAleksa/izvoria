import uuid
from typing import List
from datetime import datetime, timezone
from pydantic import BaseModel, Field, ConfigDict

from app.features.sentence_reconstruction.domain.entities import ReconstructedSentence


class ContextualizedChunk(BaseModel):
    """
    Represents a logically grouped block of sentences (typically 200-300 words).
    Contains the SLM-generated context and placeholders for future visual enrichment.
    """
    chunk_id: uuid.UUID = Field(default_factory=uuid.uuid4)

    # Time bounds for exact video frame extraction in Phase 10
    start_sec: float
    end_sec: float

    # The raw chunk text and its generated context
    original_text: str = Field(description="The grouped text from the reconstructed sentences.")
    context_string: str = Field(description="The 50-100 word situational context generated by the SLM.")

    # Placeholder for the Vision Phase (Phase 10)
    visual_descriptions: List[str] = Field(default_factory=list)

    # Preserving the strict audit trail from Phase 7 and 8
    sentences: List[ReconstructedSentence]

    model_config = ConfigDict(frozen=True)

    @property
    def combined_text(self) -> str:
        """
        The final string payload that will be embedded and BM25-indexed.
        Anthropic's Contextual Retrieval specifies prepending the context to the chunk.
        """
        return f"{self.context_string}\n\n{self.original_text}"


class ContextualizedTranscript(BaseModel):
    """
    The Aggregate Root for Phase 9.
    This replaces the PhoneticCorrectedTranscript as the primary data payload moving forward.
    """
    id: uuid.UUID = Field(default_factory=uuid.uuid4)
    source_id: uuid.UUID

    chunks: List[ContextualizedChunk] = Field(default_factory=list)

    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))

    model_config = ConfigDict(from_attributes=True)