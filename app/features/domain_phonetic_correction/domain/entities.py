import uuid
from typing import List
from datetime import datetime, timezone
from pydantic import BaseModel, Field, ConfigDict

from app.features.sentence_reconstruction.domain.entities import ReconstructedSentence

class DomainPhoneticPatch(BaseModel):
    """
    Represents a single read-only domain dictionary correction generated by the LLM.
    """
    original: str = Field(description="The exact misspelled string found in the text.")
    correction: str = Field(description="The corrected domain terminology.")

    model_config = ConfigDict(frozen=True)

class AppliedDomainCorrectionRecord(BaseModel):
    """
    An immutable audit record proving exactly what the Orchestrator changed.
    """
    sentence_id: uuid.UUID
    original_text: str
    corrected_text: str
    applied_patches: List[DomainPhoneticPatch]

    model_config = ConfigDict(frozen=True)

class DomainPhoneticCorrectedTranscript(BaseModel):
    """
    The Final Aggregate Root for Phase 8.
    """
    id: uuid.UUID = Field(default_factory=uuid.uuid4)
    source_id: uuid.UUID

    sentences: List[ReconstructedSentence] = Field(default_factory=list)
    audit_trail: List[AppliedDomainCorrectionRecord] = Field(default_factory=list)

    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))

    model_config = ConfigDict(from_attributes=True)