import uuid
from typing import Optional
from sqlalchemy import select

from app.core.database.domain.interfaces import IDatabaseManager
from app.core.database import exceptions as db_exc
from app.features.audio_extractor.domain.interfaces import IAudioExtractionRepository
from app.features.audio_extractor.domain.entities import AudioExtraction
from app.features.audio_extractor.data.models import AudioExtractionModel
from app.features.audio_extractor.exceptions.base import AudioExtractionDatabaseError


class AudioExtractionRepository(IAudioExtractionRepository):
    def __init__(self, db_manager: IDatabaseManager):
        self._db = db_manager

    def create(self, extraction: AudioExtraction) -> AudioExtraction:
        try:
            with self._db.session() as session:
                # Map Domain -> DB Model
                # created_at is automatically generated by SQLAlchemy here
                model = AudioExtractionModel(
                    id=extraction.id,
                    source_id=extraction.source_id,
                    extracted_file_id=extraction.extracted_file_id
                )
                session.add(model)

                return extraction

        except db_exc.DatabaseError as e:
            raise AudioExtractionDatabaseError(
                f"Failed to save audio extraction record: {str(e)}",
                original_exception=e
            )

    def get_latest_by_source_id(self, source_id: uuid.UUID) -> Optional[AudioExtraction]:
        try:
            with self._db.session() as session:
                stmt = (
                    select(AudioExtractionModel)
                    .where(AudioExtractionModel.source_id == source_id)
                    # We use the DB's created_at for sorting, but don't leak it to the Domain
                    .order_by(AudioExtractionModel.created_at.desc())
                    .limit(1)
                )
                model = session.execute(stmt).scalar_one_or_none()

                if not model:
                    return None

                # Map DB Model -> Domain (ignores created_at because of Pydantic config)
                return AudioExtraction.model_validate(model)

        except db_exc.DatabaseError as e:
            raise AudioExtractionDatabaseError(
                f"Failed to retrieve audio extraction record for source {source_id}: {str(e)}",
                original_exception=e
            )