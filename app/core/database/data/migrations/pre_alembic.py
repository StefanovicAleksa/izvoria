# Frozen. Before Alembic, every schema change was one of these idempotent statements, run on every boot after
# create_all(). A database from one of those builds has no alembic_version table; upgrade_to_head() runs
# create_all() and these once to bring it level with the baseline revision, then stamps it. New schema changes
# are Alembic revisions under versions/ -- never another statement here.

# session_turns: columns added with multi-turn chat, and the 'deep_research' mode renamed to 'reasoning'.
# SessionTurn parses `mode` into SessionTurnMode, so a row left on the old value fails validation and takes the
# whole conversation down with it.
SESSION_TURNS_CATCH_UP: tuple = (
    "ALTER TABLE session_turns ADD COLUMN IF NOT EXISTS mode TEXT NOT NULL DEFAULT 'chat'",
    "ALTER TABLE session_turns ADD COLUMN IF NOT EXISTS standalone_query TEXT",
    "ALTER TABLE session_turns ADD COLUMN IF NOT EXISTS evidence_chunk_ids UUID[] NOT NULL DEFAULT '{}'::uuid[]",
    "ALTER TABLE session_turns ADD COLUMN IF NOT EXISTS first_doc_number INTEGER NOT NULL DEFAULT 1",
    "UPDATE session_turns SET mode = 'reasoning' WHERE mode = 'deep_research'",
)

# jobs: JobType.DEEP_RESEARCH_REASONING became JobType.REASONING_TURN. Job.job_type is parsed into JobType, so a
# row left on the retired value makes get_job_history raise for that source.
JOBS_CATCH_UP: tuple = (
    "UPDATE jobs SET job_type = 'reasoning_turn' WHERE job_type = 'deep_research_reasoning'",
)

# research_reports: Exhaustive mode (reports before it are deep, single-round), then document anchors on evidence
# (evidence before it is transcript evidence, located by time).
RESEARCH_REPORT_CATCH_UP: tuple = (
    "ALTER TABLE research_reports ADD COLUMN IF NOT EXISTS mode TEXT NOT NULL DEFAULT 'deep'",
    "ALTER TABLE research_reports ADD COLUMN IF NOT EXISTS rounds_used INTEGER NOT NULL DEFAULT 1",
    "ALTER TABLE research_report_evidence ADD COLUMN IF NOT EXISTS anchor_kind TEXT NOT NULL DEFAULT 'time'",
    "ALTER TABLE research_report_evidence ADD COLUMN IF NOT EXISTS page_start INTEGER",
    "ALTER TABLE research_report_evidence ADD COLUMN IF NOT EXISTS page_end INTEGER",
    "ALTER TABLE research_report_evidence ADD COLUMN IF NOT EXISTS section_path TEXT",
)

# vector_chunks: document anchors. Chunks indexed before them are transcripts: time-anchored, and read in
# start_sec order, which is what the position backfill reproduces.
VECTOR_CHUNKS_CATCH_UP: tuple = (
    "ALTER TABLE vector_chunks ADD COLUMN IF NOT EXISTS anchor_kind TEXT NOT NULL DEFAULT 'time'",
    "ALTER TABLE vector_chunks ADD COLUMN IF NOT EXISTS page_start INTEGER",
    "ALTER TABLE vector_chunks ADD COLUMN IF NOT EXISTS page_end INTEGER",
    "ALTER TABLE vector_chunks ADD COLUMN IF NOT EXISTS section_path TEXT",
    "ALTER TABLE vector_chunks ADD COLUMN IF NOT EXISTS position INTEGER",
    """UPDATE vector_chunks v SET position = ordered.rn - 1
       FROM (SELECT id, ROW_NUMBER() OVER (PARTITION BY source_id ORDER BY start_sec, end_sec) AS rn
             FROM vector_chunks
             WHERE source_id IN (SELECT source_id FROM vector_chunks WHERE position IS NULL)) ordered
       WHERE v.id = ordered.id AND v.position IS NULL""",
    "CREATE INDEX IF NOT EXISTS ix_vector_chunks_source_position ON vector_chunks (source_id, position)",
    # Earlier builds kept this partial index to make the per-boot backfill check free; it has no job any more
    "DROP INDEX IF EXISTS ix_vector_chunks_position_missing",
)

# The statements above add these as TEXT, while the models (and so a fresh baseline) declare String, i.e. VARCHAR.
# Postgres treats the two alike, but a caught-up database must match the baseline exactly, or the next
# autogenerated revision would carry a spurious type change. Unbounded TEXT -> VARCHAR is binary-coercible: no
# table rewrite, and a no-op on a column that is already VARCHAR.
TYPE_ALIGNMENT: tuple = (
    "ALTER TABLE research_reports ALTER COLUMN mode TYPE VARCHAR",
    "ALTER TABLE research_report_evidence ALTER COLUMN anchor_kind TYPE VARCHAR",
    "ALTER TABLE vector_chunks ALTER COLUMN anchor_kind TYPE VARCHAR",
    "ALTER TABLE vector_chunks ALTER COLUMN section_path TYPE VARCHAR",
)

PRE_ALEMBIC_CATCH_UP: tuple = (*SESSION_TURNS_CATCH_UP, *JOBS_CATCH_UP, *RESEARCH_REPORT_CATCH_UP,
                               *VECTOR_CHUNKS_CATCH_UP, *TYPE_ALIGNMENT)


def catch_up_statements(existing_tables: set) -> list:
    """
    The statements for the tables this old database already has, in order. They run before the baseline, whose
    indexes need the columns they add (ix_vector_chunks_source_position needs `position`); a table the database
    lacks is created by the baseline instead, already in the baseline's shape.
    """
    return [statement for statement in PRE_ALEMBIC_CATCH_UP
            if statement.startswith("DROP INDEX IF EXISTS") or _table_of(statement) in existing_tables]


def _table_of(statement: str) -> str:
    words = statement.replace("(", " ").split()
    for keyword in ("TABLE", "UPDATE", "ON"):
        if keyword in words:
            return words[words.index(keyword) + 1]
    raise ValueError(f"No table in catch-up statement: {statement[:60]}")
