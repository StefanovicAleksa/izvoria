const catalogs: Record<Lang, Record<string, string>> = { en: {}, sr: SERBIAN };

interface I18n {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (text: string) => string;
}

const I18nContext = createContext<I18n>({ lang: "en", setLang: () => {}, t: (s) => s });

function remembered(fallback: Lang): Lang {
  try {
    const value = localStorage.getItem("onyx.displayLanguage");
    return value === "en" || value === "sr" ? value : fallback;
  } catch {
    return fallback;
  }
}

export function I18nProvider({ initial, children }: { initial: Lang; children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => remembered(initial));
  const value = useMemo<I18n>(
    () => ({
      lang,
      setLang: (next) => {
        setLangState(next);
        try {
          localStorage.setItem("onyx.displayLanguage", next);
        } catch {
          /* private window: the choice lasts for this page only */
        }
      },
      t: (text) => catalogs[lang][text] ?? text,
    }),
    [lang],
  );
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);

