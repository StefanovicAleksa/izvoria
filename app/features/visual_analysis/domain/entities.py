import uuid
from typing import List
from datetime import datetime, timezone
from pydantic import BaseModel, Field, ConfigDict


class FrameAnalysis(BaseModel):
    """
    Represents the semantic text description of a single physical frame,
    generated by a Vision-Language Model (VLM).
    """
    frame_id: uuid.UUID = Field(description="The UUID of the original ExtractedFrame.")
    description: str = Field(description="The contextualized text description generated by the VLM.")

    model_config = ConfigDict(frozen=True)


class ChunkVisualAnalysis(BaseModel):
    """
    The Aggregate Root for the Visual Analysis phase (Phase 10).
    Aggregates all individual frame descriptions for a specific contextual text chunk.
    Acts as the single source of truth for crash recovery and RAG ingestion.
    """
    id: uuid.UUID = Field(default_factory=uuid.uuid4)

    source_id: uuid.UUID = Field(description="The UUID of the original Video Source.")
    chunk_id: uuid.UUID = Field(description="The UUID of the target ContextualizedChunk.")

    analyses: List[FrameAnalysis] = Field(default_factory=list)

    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))

    model_config = ConfigDict(from_attributes=True)