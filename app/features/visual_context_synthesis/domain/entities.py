import uuid
from typing import List
from datetime import datetime, timezone
from pydantic import BaseModel, Field, ConfigDict


class VisualContextFrame(BaseModel):
    """
    A lightweight pointer to a validated frame.
    Used by the UI to retrieve and display the actual .jpg image when the RAG cites this visual context.
    """
    frame_id: uuid.UUID
    timestamp_sec: float

    model_config = ConfigDict(frozen=True)


class VisualTimelineChunk(BaseModel):
    """
    Represents the final visual payload for a specific 250-word segment of the video.
    """
    # Matches the chunk_id from Phase 9's ContextualizedChunk so Phase 15 can easily join them
    chunk_id: uuid.UUID

    # The 1-2 sentence paragraph generated by the SLM summarizing the fuzzy visual timeline
    visual_context_string: str = Field(default="")

    # The deduplicated timeline of valid frames
    visual_evidence: List[VisualContextFrame] = Field(default_factory=list)

    model_config = ConfigDict(frozen=True)


class VisualTimeline(BaseModel):
    """
    The Aggregate Root for Phase 14.
    Represents the complete chronological visual narrative of the entire video.
    """
    id: uuid.UUID = Field(default_factory=uuid.uuid4)
    source_id: uuid.UUID = Field(default_factory=uuid.uuid4)

    visual_chunks: List[VisualTimelineChunk] = Field(default_factory=list)

    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))

    model_config = ConfigDict(from_attributes=True)